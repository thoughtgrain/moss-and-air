def pack(face, w, h):
    out = []
    for c in range(32, 96):
        art = face.get(chr(c), face["?"])
        assert len(art) == h and all(len(r) == w and set(r) <= set(".#") for r in art), chr(c)
        out.append([int(r.replace(".", "0").replace("#", "1"), 2) for r in art])
    return out


def table(name, rows):
    body = ",\n".join("    {" + ", ".join(f"0x{b:02x}" for b in g) + f"}}  /* {chr(32 + i)!r} */"
                      for i, g in enumerate(rows))
    return f"static const uint8_t {name}[64][{len(rows[0])}] = {{\n{body}\n}};\n"


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    text = ("/* generated by tools/gen_px_font.py: Bryo's bitmap faces (characters 32..95, a byte per row) */\n"
            "#pragma once\n#include <stdint.h>\n\n" + table("PX5", pack(PX5, 5, 7)) + "\n" + table("PX3", pack(PX3, 3, 5)))
    with open(sys.argv[1], "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
