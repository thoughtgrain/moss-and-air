#include "tape.c"                /* TAPE: the ADPCM looper, the factory reels */
#include "chain.c"               /* the four tracks, rendered per control block */

/* ------------------------------------------------------------- I/O --- */
#include "usb.c"
#if FELUCCA_UART
#include "midi_uart.c"
#endif
#include "audio.c"

/* -------------------------------------------------------------- UI --- */
#include "icons.c"
#include "panel.c"               /* the panel map, the settings in RAM, HARDWARE CALIBRATION */

/* ---------------------------------------------------------- stores --- */
#if FELUCCA_FLASH
#include "fm1_flash.h"
#include "storage_hw.c"
#include "storage.c"
#endif
#include "settings.c"            /* the settings record (shared with Felucca installs: settings.c) */

#include "ui_px.c"              /* the dot grid: bitmap type, strokes, the pictograms */
#include "ui.c"
#include "ui_viz.c"              /* the visualization panel */
#include "ui_input.c"
#if FELUCCA_OTA
#include "ota.c"
#include "ota_hw.c"
#endif
#if FELUCCA_CDC
#include "console.c"
#endif
#include "main.c"
